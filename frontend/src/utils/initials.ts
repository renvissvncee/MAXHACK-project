export function getInitials(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  if (parts.length === 0) return "?";
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return (parts[0][0] + parts[1][0]).toUpperCase();
}

const IDENTITY_GRADIENTS = ["identity-1", "identity-2", "identity-3"];

/** Deterministic gradient pick so the same person always gets the same color. */
export function getIdentityGradient(seed: string): string {
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash * 31 + seed.charCodeAt(i)) >>> 0;
  }
  return IDENTITY_GRADIENTS[hash % IDENTITY_GRADIENTS.length];
}
